import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bundleHash } from './bundle.mjs';

const root = fileURLToPath(new URL('../tgcloud/', import.meta.url));
const repo = fileURLToPath(new URL('../', import.meta.url));
const args = {};
for (let i = 2; i < process.argv.length; i += 1) {
  if (process.argv[i].startsWith('--')) args[process.argv[i].slice(2)] = process.argv[i + 1];
}

const hash = bundleHash(root);
const writeRelease = Boolean(args.release || args.verified === 'true');

if (writeRelease && !args.commit) {
  args.commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: repo, encoding: 'utf8' }).trim();
}

// Only a clean tree whose app source still matches --commit may claim the
// deployed source was verified. Release/stamp commits may follow --commit, but
// they may not change tgcloud source (build.js is the stamp itself).
if (args.verified === 'true') {
  if (!args.release || args.release === 'dev') {
    throw new Error('refusing --verified true: --release is required');
  }
  if (!args.commit) throw new Error('refusing --verified true: --commit is required');
  const dirty = execFileSync('git', ['status', '--porcelain'], { cwd: repo, encoding: 'utf8' }).trim();
  if (dirty) throw new Error('refusing --verified true: the working tree is dirty');
  try {
    execFileSync('git', ['rev-parse', '--verify', `${args.commit}^{commit}`], { cwd: repo, stdio: 'ignore' });
    execFileSync('git', ['merge-base', '--is-ancestor', args.commit, 'HEAD'], { cwd: repo, stdio: 'ignore' });
  } catch {
    throw new Error('refusing --verified true: --commit must be an ancestor of HEAD');
  }
  const changed = execFileSync(
    'git',
    ['diff', '--name-only', `${args.commit}..HEAD`, '--', 'tgcloud'],
    { cwd: repo, encoding: 'utf8' },
  ).trim().split(/\r?\n/).filter((path) => path && path !== 'tgcloud/lib/build.js');
  if (changed.length) {
    throw new Error(`refusing --verified true: app source changed after --commit (${changed.join(', ')})`);
  }
}

const build = {
  release: args.release ?? 'dev',
  commit: args.commit ?? 'local',
  bundleHash: hash,
  verified: args.verified === 'true',
};

writeFileSync(
  join(root, 'lib', 'build.js'),
  `// generated by tools/gen-build.mjs at deploy; do not edit\nexport const BUILD = ${JSON.stringify(build)};\n`,
);

if (writeRelease) {
  const manifest = {
    name: 'AmnPM',
    release: build.release,
    commit: build.commit,
    bundleHash: build.bundleHash,
    verified: build.verified,
  };
  writeFileSync(
    join(repo, 'release', 'manifest.json'),
    `${JSON.stringify(manifest, null, 2)}\n`,
  );
  writeFileSync(
    join(repo, 'release', 'notes.md'),
    `<!-- generated by tools/gen-build.mjs; do not edit -->\n` +
    `Anonymous link-based Telegram bot.\n\n` +
    `Release: ${build.release}\n\n` +
    `Bundle hash: ${build.bundleHash}\n\n` +
    `Code commit: ${build.commit}\n\n` +
    `The bundle hash covers every \`.js\` file under \`tgcloud/\` except \`build.js\` and\n` +
    `\`secret.js\`, in sorted walk order (relative path + NUL + bytes). CI fails if\n` +
    `\`build.js\` or \`release/manifest.json\` is stale. The hash is a supply-chain\n` +
    `check, not proof of the running Telegram Serverless process.\n`,
  );
}

console.log(JSON.stringify(build));

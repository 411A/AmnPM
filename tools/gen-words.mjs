import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2];
if (!src) {
  console.error('usage: node tools/gen-words.mjs <eff_large_wordlist.txt>');
  process.exit(1);
}

const all = readFileSync(src, 'utf8')
  .split('\n')
  .map((line) => line.split('\t')[1]?.trim())
  .filter((word) => word && /^[a-z]+$/.test(word));

if (all.length < 4096) {
  console.error(`need 4096 words, found ${all.length}`);
  process.exit(1);
}

const words = Array.from({ length: 4096 }, (_, i) => all[Math.floor((i * all.length) / 4096)]);
if (new Set(words).size !== 4096) {
  console.error('duplicate words after sampling');
  process.exit(1);
}

const out = new URL('../tgcloud/lib/words.js', import.meta.url);
writeFileSync(out, `// generated by tools/gen-words.mjs from the EFF large wordlist; data only\nexport const WORDS = ${JSON.stringify(words)};\n`);
console.log(`wrote ${words.length} words`);

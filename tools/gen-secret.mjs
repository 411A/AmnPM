// Build-time secret generator. Serverless has no runtime environment, so the
// named key domains are materialized into tgcloud/lib/secret.js (gitignored).
//
//   cp .env.example .env      # fill the named key groups
//   node tools/gen-secret.mjs
//
// With no .env content, existing keys are preserved and missing domains are
// generated. Existing content keys are never replaced, so live data stays
// readable. Secrets are never printed.
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const secretPath = join(root, 'tgcloud', 'lib', 'secret.js');
const envPath = join(root, '.env');

function parseEnv(text) {
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const index = line.indexOf('=');
    if (index < 0) continue;
    const key = line.slice(0, index).trim();
    let value = line.slice(index + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"'))
      || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

function hexKey() {
  return randomBytes(32).toString('hex');
}

function validate(name, keys) {
  for (const [version, key] of Object.entries(keys)) {
    if (typeof key !== 'string' || !/^[0-9a-fA-F]{64}$/.test(key) || /^0+$/.test(key)) {
      throw new Error(`${name} ${version} must be 32 nonzero bytes of hex`);
    }
  }
}

function parseGroup(value, fallback) {
  if (!value) return fallback;
  try {
    return JSON.parse(value);
  } catch {
    throw new Error('a *_KEYS_JSON value is not valid JSON');
  }
}

let existing = {};
if (existsSync(secretPath)) {
  existing = await import(pathToFileURL(secretPath).href);
}
const env = existsSync(envPath) ? parseEnv(readFileSync(envPath, 'utf8')) : {};

const content = parseGroup(env.CONTENT_KEYS_JSON, existing.KEYS ?? {});
const identity = parseGroup(
  env.IDENTITY_KEYS_JSON,
  existing.IDENTITY_KEYS ?? { 1: hexKey() },
);
const action = parseGroup(
  env.ACTION_KEYS_JSON,
  existing.ACTION_KEYS ?? { 1: hexKey() },
);
const contentVersion = Number(
  env.CURRENT_CONTENT_KEK_VERSION ?? existing.CURRENT_KEK_VERSION ?? 1,
);
const identityVersion = Number(
  env.CURRENT_IDENTITY_KEK_VERSION ?? existing.CURRENT_IDENTITY_KEK_VERSION ?? 1,
);
const actionVersion = Number(
  env.CURRENT_ACTION_KEK_VERSION ?? existing.CURRENT_ACTION_KEK_VERSION ?? 1,
);

if (!Object.keys(content).length) throw new Error('no content keys found');
validate('content KEK', content);
validate('identity KEK', identity);
validate('action KEK', action);
if (!content[contentVersion]) throw new Error(`missing content key version ${contentVersion}`);
if (!identity[identityVersion]) throw new Error(`missing identity key version ${identityVersion}`);
if (!action[actionVersion]) throw new Error(`missing action key version ${actionVersion}`);

const body = `// generated by tools/gen-secret.mjs at deploy; do not commit
export const KEYS = ${JSON.stringify(content, null, 2)};
export const CURRENT_KEK_VERSION = ${contentVersion};
export const IDENTITY_KEYS = ${JSON.stringify(identity, null, 2)};
export const CURRENT_IDENTITY_KEK_VERSION = ${identityVersion};
export const ACTION_KEYS = ${JSON.stringify(action, null, 2)};
export const CURRENT_ACTION_KEK_VERSION = ${actionVersion};
`;
writeFileSync(secretPath, body);

console.log(JSON.stringify({
  contentVersions: Object.keys(content).map(Number),
  identityVersions: Object.keys(identity).map(Number),
  actionVersions: Object.keys(action).map(Number),
  currentContent: contentVersion,
  currentIdentity: identityVersion,
  currentAction: actionVersion,
}));

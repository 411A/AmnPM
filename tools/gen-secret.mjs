// Build-time secret generator. Serverless has no runtime environment, so the
// named key domains are materialized into tgcloud/lib/secret.js (gitignored).
//
//   cp .env.example .env      # fill only NEW versions; old versions are merged
//   node tools/gen-secret.mjs
//
// With no .env, existing keys are preserved and missing domains are generated.
// The tool never replaces a key under an existing version and never drops a
// version. Secrets are never printed.
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const secretPath = join(root, 'tgcloud', 'lib', 'secret.js');
const envPath = join(root, '.env');

export function hexKey() {
  return randomBytes(32).toString('hex');
}

export function parseEnv(text) {
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const index = line.indexOf('=');
    if (index < 0) continue;
    const key = line.slice(0, index).trim();
    let value = line.slice(index + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"'))
      || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

export function parseGroup(value, fallback = {}) {
  if (!value) return fallback;
  try {
    return JSON.parse(value);
  } catch {
    throw new Error('a *_KEYS_JSON value is not valid JSON');
  }
}

function validate(name, keys) {
  for (const [version, key] of Object.entries(keys)) {
    if (typeof key !== 'string' || !/^[0-9a-fA-F]{64}$/.test(key) || /^0+$/.test(key)) {
      throw new Error(`${name} ${version} must be 32 nonzero bytes of hex`);
    }
  }
}

function merge(name, existing, incoming) {
  const merged = { ...existing };
  for (const [version, key] of Object.entries(incoming)) {
    const previous = merged[version];
    if (previous && previous.toLowerCase() !== String(key).toLowerCase()) {
      throw new Error(
        `refusing to replace ${name} key version ${version}; add a new version instead`,
      );
    }
    merged[version] = String(key);
  }
  return merged;
}

function pickCurrent(name, merged, envValue, existingValue) {
  const values = Object.keys(merged).map(Number).sort((a, b) => b - a);
  const current = Number(envValue ?? existingValue ?? values[0]);
  if (!merged[current]) {
    throw new Error(`current ${name} version ${current} is not in the merged key group`);
  }
  return current;
}

export function buildSecret({ existing = {}, env = {}, randomKey = hexKey, init = false } = {}) {
  const existingContent = existing.KEYS ?? {};
  const incomingContent = parseGroup(env.CONTENT_KEYS_JSON, {});
  if (!Object.keys(existingContent).length
    && !Object.keys(incomingContent).length
    && !init) {
    throw new Error(
      'no existing secret.js and no CONTENT_KEYS_JSON; restore the keys or use --init only for a new deployment',
    );
  }

  const content = merge('content', existingContent, incomingContent);
  const identity = merge(
    'identity',
    existing.IDENTITY_KEYS ?? {},
    parseGroup(env.IDENTITY_KEYS_JSON, {}),
  );
  const action = merge(
    'action',
    existing.ACTION_KEYS ?? {},
    parseGroup(env.ACTION_KEYS_JSON, {}),
  );

  for (const [name, group] of [['content', content], ['identity', identity], ['action', action]]) {
    if (!Object.keys(group).length) {
      group[1] = randomKey();
    }
    validate(name, group);
  }

  const contentVersion = pickCurrent(
    'content',
    content,
    env.CURRENT_CONTENT_KEK_VERSION,
    existing.CURRENT_KEK_VERSION,
  );
  const identityVersion = pickCurrent(
    'identity',
    identity,
    env.CURRENT_IDENTITY_KEK_VERSION,
    existing.CURRENT_IDENTITY_KEK_VERSION,
  );
  const actionVersion = pickCurrent(
    'action',
    action,
    env.CURRENT_ACTION_KEK_VERSION,
    existing.CURRENT_ACTION_KEK_VERSION,
  );

  // Owner/sender chat ids do not store an identity version yet. Advancing the
  // identity current version would make rows sealed with the old current
  // unreadable, so fail closed instead of creating a data lock.
  if (existing.CURRENT_IDENTITY_KEK_VERSION
    && Number(existing.CURRENT_IDENTITY_KEK_VERSION) !== identityVersion) {
    throw new Error(
      'refusing to change CURRENT_IDENTITY_KEK_VERSION: owner/sender chat ids '
      + 'do not store an identity version yet; keep the current identity version '
      + 'or add the fallback/re-encryption first',
    );
  }

  return {
    content: { keys: content, current: contentVersion },
    identity: { keys: identity, current: identityVersion },
    action: { keys: action, current: actionVersion },
  };
}

export function renderSecret(built) {
  return `// generated by tools/gen-secret.mjs at deploy; do not commit
export const KEYS = ${JSON.stringify(built.content.keys, null, 2)};
export const CURRENT_KEK_VERSION = ${built.content.current};
export const IDENTITY_KEYS = ${JSON.stringify(built.identity.keys, null, 2)};
export const CURRENT_IDENTITY_KEK_VERSION = ${built.identity.current};
export const ACTION_KEYS = ${JSON.stringify(built.action.keys, null, 2)};
export const CURRENT_ACTION_KEK_VERSION = ${built.action.current};
`;
}

async function main() {
  const existing = existsSync(secretPath)
    ? await import(pathToFileURL(secretPath).href)
    : {};
  const env = existsSync(envPath) ? parseEnv(readFileSync(envPath, 'utf8')) : {};
  const init = process.argv.includes('--init');
  const built = buildSecret({ existing, env, init });
  writeFileSync(secretPath, renderSecret(built));
  console.log(JSON.stringify({
    contentVersions: Object.keys(built.content.keys).map(Number),
    identityVersions: Object.keys(built.identity.keys).map(Number),
    actionVersions: Object.keys(built.action.keys).map(Number),
    currentContent: built.content.current,
    currentIdentity: built.identity.current,
    currentAction: built.action.current,
  }));
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  main().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}
